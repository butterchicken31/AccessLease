// IN-MEMORY STATE: current dataset, workflow state per item, and the audit log.
// Lives on globalThis so it survives Next.js hot reloads.
// NOTE: On Vercel (serverless), memory can reset between requests.
// For the live demo, run locally or replace this file with a database later.

import { createHash } from "crypto";
import policy from "../data/policy.json";
import demoData from "../data/dataset.json";
import edgeData from "../data/edgeCases.json";
import { analyze, parseDate } from "./engine.js";
import { getNow } from "./now.js";
import { STATE_LABELS, actionsFor } from "./workflow.js";

const DATASETS = {
  demo: demoData,
  edge: edgeData,
};

const CLOSED = ["revoked", "exception_accepted"];

const fresh = (key) => ({
  key,
  dataset: structuredClone(DATASETS[key]),
  workflow: {},
});

function root() {
  if (!globalThis.__accesslease) {
    globalThis.__accesslease = {
      s: fresh("demo"),
      audit: [],
    };
  }

  return globalThis.__accesslease;
}

// ---------- audit log ----------
// The audit log is hash-chained.
// Editing an older entry breaks the chain.

function hashEntry(entry) {
  const { hash, ...rest } = entry;

  return createHash("sha256")
    .update(JSON.stringify(rest))
    .digest("hex");
}

function appendAudit(partial, timestamp = getNow()) {
  const r = root();

  const prevHash = r.audit.length
    ? r.audit[r.audit.length - 1].hash
    : "GENESIS";

  const isoTimestamp = timestamp.toISOString();

  const entry = {
    seq: r.audit.length + 1,
    ts: isoTimestamp,
    asOf: isoTimestamp,
    ...partial,
    prevHash,
  };

  entry.hash = hashEntry(entry);

  r.audit.push(entry);

  return entry;
}

function verify(entries) {
  let prev = "GENESIS";

  for (const entry of entries) {
    if (
      entry.prevHash !== prev ||
      hashEntry(entry) !== entry.hash
    ) {
      return {
        valid: false,
        brokenAt: entry.seq,
      };
    }

    prev = entry.hash;
  }

  return {
    valid: true,
    brokenAt: null,
  };
}

export function getAudit({
  simulateTamper = false,
} = {}) {
  const entries = root().audit.map((entry) => ({
    ...entry,
  }));

  const real = verify(entries);

  let tamper = null;

  if (simulateTamper && entries.length) {
    const copy = entries.map((entry) => ({
      ...entry,
    }));

    copy[0].reason =
      (copy[0].reason || "") + " (edited later)";

    tamper = verify(copy);
  }

  return {
    entries: entries.slice().reverse(),
    chainValid: real.valid,
    brokenAt: real.brokenAt,
    tamperTest: tamper,
  };
}

// ---------- findings ----------

export function getFindings() {
  const { s } = root();
  const now = getNow();

  const findings = analyze(
    s.dataset,
    policy,
    now
  ).map((finding) => {
    const workflow = s.workflow[finding.itemId];

    const state =
      finding.status === "resolved"
        ? "revoked"
        : workflow?.state ||
          (finding.status === "compliant"
            ? "none"
            : "flagged");

    let allowed = [];

    if (
      ["violation", "needs_review"].includes(
        finding.status
      )
    ) {
      allowed = actionsFor(state).filter(
        (action) =>
          action.action !== "emergency_revoke" ||
          finding.status === "violation"
      );
    }

    return {
      ...finding,
      workflow: {
        state,
        label: STATE_LABELS[state] || state,
        updatedAt: workflow?.updatedAt || null,
      },
      allowedActions: allowed,
    };
  });

  const open = (finding) =>
    ["violation", "needs_review"].includes(
      finding.status
    ) &&
    !CLOSED.includes(finding.workflow.state);

  findings.sort(
    (a, b) =>
      Number(open(b)) - Number(open(a)) ||
      b.priorityScore - a.priorityScore
  );

  const count = (status) =>
    findings.filter(
      (finding) => finding.status === status
    ).length;

  return {
    asOf: now.toISOString(),

    dataset: {
      key: s.key,
      name: s.dataset.meta?.name || s.key,
    },

    summary: {
      total: findings.length,
      violation: count("violation"),
      needs_review: count("needs_review"),
      compliant: count("compliant"),
      resolved: count("resolved"),

      exceptions: findings.filter(
        (finding) =>
          finding.workflow.state ===
          "exception_accepted"
      ).length,
    },

    findings,
  };
}

export const getFinding = (id) =>
  getFindings().find(
    (finding) => finding.id === id
  ) || null;

// ---------- reviewer decisions ----------

export function applyReview({
  findingId,
  action,
  reviewer,
  reason,
  newExpiry,
}) {
  const { s } = root();

  // Capture the centralized clock once so every timestamp
  // generated by this review uses the same instant.
  const now = getNow();

  const before = getFindings().findings;

  const finding = before.find(
    (item) => item.id === findingId
  );

  if (!finding) {
    return {
      status: 404,
      error: "Finding not found.",
    };
  }

  if (
    !reviewer ||
    String(reviewer).trim().length < 2
  ) {
    return {
      status: 400,
      error: "Reviewer name is required.",
    };
  }

  if (
    !reason ||
    String(reason).trim().length < 5
  ) {
    return {
      status: 400,
      error:
        "A reason (at least 5 characters) is required.",
    };
  }

  const allowed = finding.allowedActions.find(
    (item) => item.action === action
  );

  if (!allowed) {
    return {
      status: 409,
      error: `"${action}" is not allowed while the item is in state "${finding.workflow.label}".`,
    };
  }

  const list =
    finding.kind === "delegation"
      ? s.dataset.delegations
      : s.dataset.grants;

  const item = list[finding.index];

  const changes = [];

  if (
    action === "revoke" ||
    action === "emergency_revoke"
  ) {
    changes.push({
      field: `${finding.itemId}.status`,
      before: item.status || "active",
      after: "revoked",
    });

    item.status = "revoked";
  }

  if (action === "extend") {
    const parsed = parseDate(newExpiry, true);

    const max =
      policy.limits?.maxExtensionDays ?? 30;

    if (parsed.state !== "ok") {
      return {
        status: 400,
        error: "Pick a valid new expiry date.",
      };
    }

    if (parsed.date <= now) {
      return {
        status: 400,
        error: "The new expiry must be in the future.",
      };
    }

    if (
      parsed.date >
      new Date(now.getTime() + max * 86400000)
    ) {
      return {
        status: 400,
        error: `Policy allows extending at most ${max} days from today.`,
      };
    }

    changes.push({
      field: `${finding.itemId}.expiresAt`,
      before: item.expiresAt || "(none)",
      after: String(newExpiry),
    });

    item.expiresAt = String(newExpiry);
  }

  const to = allowed.to;

  // Workflow and audit timestamps use the same clock value.
  s.workflow[finding.itemId] = {
    state: to,
    updatedAt: now.toISOString(),
  };

  const entry = appendAudit(
    {
      reviewer: String(reviewer).trim(),
      action,
      itemId: finding.itemId,
      findingId: finding.id,
      fromState: finding.workflow.state,
      toState: to,
      reason: String(reason).trim(),
      changes,
    },
    now
  );

  const after = getFindings().findings;

  const wasBad = new Set(
    before
      .filter(
        (item) => item.status === "violation"
      )
      .map((item) => item.id)
  );

  const newViolations = after
    .filter(
      (item) =>
        item.status === "violation" &&
        !wasBad.has(item.id)
    )
    .map((item) => item.id);

  return {
    status: 200,
    ok: true,
    entry,
    finding: after.find(
      (item) => item.id === findingId
    ),
    newViolations,
  };
}

// ---------- datasets ----------

export function loadDataset(key) {
  const r = root();

  // "reset" reloads the currently active dataset.
  const target =
    key === "reset" ? r.s.key : key;

  if (!DATASETS[target]) {
    return {
      status: 400,
      error: "Unknown dataset.",
    };
  }

  r.s = fresh(target);

  appendAudit({
    reviewer: "system",
    action:
      key === "reset"
        ? "reset_dataset"
        : "load_dataset",
    itemId: "-",
    findingId: "-",
    fromState: "-",
    toState: "-",
    reason: `Dataset "${target}" loaded; workflow state cleared`,
    changes: [],
  });

  return {
    status: 200,
    ok: true,
    dataset: {
      key: target,
      name: r.s.dataset.meta?.name,
    },
  };
}

export function currentDataset() {
  const { s } = root();

  return {
    key: s.key,
    name: s.dataset.meta?.name,
    description: s.dataset.meta?.description,
    available: Object.keys(DATASETS),
  };
}

// ---------- permission graph ----------

export function getGraph() {
  const { findings } = getFindings();
  const { s } = root();

  const idMap = new Map(
    (s.dataset.identities || []).map(
      (identity) => [identity.id, identity]
    )
  );

  const resourceMap = new Map(
    (s.dataset.resources || []).map(
      (resource) => [resource.id, resource]
    )
  );

  const edges = findings
    .filter(
      (finding) =>
        finding.identityId &&
        finding.resourceId &&
        idMap.has(finding.identityId) &&
        resourceMap.has(finding.resourceId)
    )
    .map((finding) => ({
      findingId: finding.id,
      itemId: finding.itemId,
      kind: finding.kind,
      from: finding.identityId,
      to: finding.resourceId,
      status: finding.status,
      role: finding.role,
      score: finding.priorityScore,
    }));

  const ids = new Set(
    edges.map((edge) => edge.from)
  );

  const resources = new Set(
    edges.map((edge) => edge.to)
  );

  return {
    identities: [...ids].map((id) => {
      const identity = idMap.get(id);

      return {
        id,
        name: identity.name || id,
        type: identity.type,
        status: identity.status,
      };
    }),

    resources: [...resources].map((id) => {
      const resource = resourceMap.get(id);

      return {
        id,
        name: resource.name || id,
        sensitivity: resource.sensitivity,
      };
    }),

    edges,
  };
}